#' Plot Cell Type Proportions as a Stacked Barplot
#'
#' This function calculates the proportion of each cell type within specified groups
#' and visualizes them as a stacked barplot.
#'
#' @param seurat_obj A Seurat object containing the metadata for cell groups and types.
#' @param group_col The name of the metadata column in `seurat_obj` that defines the groups (e.g., "Group").
#' @param cluster_col The name of the metadata column in `seurat_obj` that defines the cell types/clusters (e.g., "Major_celltype").
#' @param plot_colors A named character vector for cell type colors. If NULL, default colors will be used, and a warning will be issued.
#'
#' @return A ggplot object representing the stacked barplot of cell type proportions.
#'
#' @importFrom Seurat GetAssayData
#' @importFrom dplyr as_tibble group_by mutate ungroup select
#' @importFrom ggplot2 ggplot aes geom_col scale_fill_manual scale_y_continuous labs theme element_text expansion
#' @importFrom stats table
#' @importFrom scales percent hue_pal
#' @importFrom rlang sym
#'
plot_cell_proportion_barplot <- function(seurat_obj,
                                         group_col,
                                         cluster_col,
                                         plot_colors = NULL) {
  
  # 1. Load required packages
  if (!requireNamespace("Seurat", quietly = TRUE)) stop("Package 'Seurat' is required.")
  if (!requireNamespace("dplyr", quietly = TRUE)) stop("Package 'dplyr' is required.")
  if (!requireNamespace("ggplot2", quietly = TRUE)) stop("Package 'ggplot2' is required.")
  if (!requireNamespace("scales", quietly = TRUE)) stop("Package 'scales' is required.")
  
  # 2. Data Preparation
  # Extract relevant metadata columns
  df_meta <- seurat_obj@meta.data %>%
    dplyr::select(!!sym(group_col), !!sym(cluster_col))
  
  # Calculate proportions per group
  df <- as.data.frame(table(df_meta[[group_col]], df_meta[[cluster_col]])) %>%
    dplyr::rename(Group = Var1, celltype = Var2, Count = Freq) %>%
    dplyr::group_by(Group) %>%
    dplyr::mutate(Freq = Count / sum(Count) * 100) %>% # Convert to percentage
    dplyr::ungroup()
  
  # 3. Handle plot colors
  all_celltypes <- unique(df$celltype)
  if (is.null(plot_colors)) {
    warning("plot_colors not provided. Using default colors generated by scales::hue_pal().")
    default_colors <- scales::hue_pal()(length(all_celltypes))
    plot_colors <- setNames(default_colors, all_celltypes)
  }
  
  # 4. Create the plot
  p1 <- ggplot2::ggplot(df, aes(x = Group, y = Freq, fill = celltype)) +
    ggplot2::geom_col(position = "stack", alpha = 0.6, width = 0.7, color = "black", linewidth = 0.2) +
    ggplot2::scale_fill_manual(values = plot_colors) + # Use scale_fill_manual for custom colors
    ggplot2::scale_y_continuous(expand = expansion(mult = c(0, 0.01)), labels = scales::percent_format(scale = 1)) + # Use percent_format
    ggplot2::labs(
      x = "Group", # Keep x-axis label for clarity
      y = "Cell Percentage (%)"
    ) +
    ggplot2::theme_minimal() +
    ggplot2::theme(
      plot.title = element_text(hjust = 0.5, size = 16, face = "bold"),
      axis.text.y = element_text(size = 12, color = "black"),
      axis.text.x = element_text(size = 12, color = "black", angle = 30, vjust = 0.5,hjust = 0.5,),
      axis.title = element_text(size = 14, face = "bold"),
      legend.position = "right",
      legend.title = element_text(size = 14, face = "bold"),
      legend.text = element_text(size = 12),
      panel.grid.major.y = element_blank(), # Remove horizontal grid lines
      panel.grid.minor = element_blank(),
      panel.grid.major.x = element_line(color = "gray85", linetype = "dotted"), # Keep subtle vertical grid lines for percentage
      axis.line = element_line(color = "black", linewidth = 0.5) # Add axis lines
    )
  
  return(p1)
}

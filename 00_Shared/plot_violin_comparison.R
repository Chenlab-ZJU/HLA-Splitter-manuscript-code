#' Plot Gene Expression Comparison Across Groups with Violin Plots
#'
#' This function generates violin plots for selected genes/features, comparing their
#' expression across different groups within a Seurat object. It includes boxplots
#' within violins, custom themes, and adds statistical significance markers via ggpubr.
#'
#' @param seurat_obj A Seurat object containing expression data and metadata.
#' @param features_to_plot A character vector of gene names or features (e.g., scores) to plot.
#' @param group_col The name of the metadata column in `seurat_obj` that defines
#'   the experimental groups (e.g., "Group", "Condition"). This column will be used for the X-axis grouping.
#' @param comparison_groups A list of character vectors specifying the pairwise comparisons
#'   to perform for statistical tests (e.g., list(c("GroupA", "GroupB"))). These comparisons
#'   will be drawn between groups on the X-axis.
#' @param plot_colors A named character vector for the fill colors of the groups.
#'   Names should correspond to the group names in `group_col`. If NULL, default
#' @return A combined ggplot object of all generated violin plots.
#'
#' @importFrom Seurat VlnPlot
#' @importFrom ggplot2 aes geom_boxplot labs theme_minimal theme element_text element_blank expansion scale_y_continuous
#' @importFrom ggpubr stat_compare_means
#' @importFrom scales hue_pal
#' @importFrom patchwork wrap_plots
#' @importFrom rlang sym
#' @importFrom dplyr select mutate
#'
plot_violin_comparison <- function(seurat_obj,
                                   features_to_plot,
                                   group_col,
                                   ncol = 4,
                                   comparison_groups,
                                   plot_colors = NULL) {
  
  # 1. Check for required packages
  required_packages <- c("Seurat", "ggplot2", "ggpubr", "scales", "patchwork", "dplyr", "rlang")
  for (pkg in required_packages) {
    if (!requireNamespace(pkg, quietly = TRUE)) {
      stop(paste0("Package '", pkg, "' is required but not installed. Please install it."))
    }
  }
  
  # Ensure the group_col in seurat_obj metadata is a factor
  if (!is.factor(seurat_obj@meta.data[[group_col]])) {
    seurat_obj@meta.data[[group_col]] <- factor(seurat_obj@meta.data[[group_col]])
  }
  
  # Handle plot colors
  all_groups_in_data <- levels(seurat_obj@meta.data[[group_col]])
  if (is.null(plot_colors)) {
    warning("`plot_colors` not provided. Using default colors generated by `scales::hue_pal()`.")
    default_colors <- scales::hue_pal()(length(all_groups_in_data))
    plot_colors <- setNames(default_colors, all_groups_in_data)
  }
  
  # 2. Use Seurat::VlnPlot() to generate base violin plots
  # `combine = FALSE` returns a list of ggplot objects, one for each feature
  plots_violins <- Seurat::VlnPlot(
    object = seurat_obj,
    features = features_to_plot,
    cols = plot_colors,
    pt.size = 0, # Remove individual points for cleaner violins
    group.by = group_col,
    log = FALSE,
    combine = FALSE # Crucial for post-processing individual plots
  )
  
  # 3. Iterate through each plot to add customizations and statistical tests
  modified_plots <- list()
  for (i in 1:length(plots_violins)) {
    current_plot <- plots_violins[[i]]
    
    # Apply theme and add components
    p_final <- current_plot +
      ggplot2::geom_boxplot(width = 0.1, fill = "white", outliers = FALSE, color = "black", linewidth = 0.7) +
      ggplot2::theme(
        axis.text.x = element_text(angle = 30, hjust = 1, vjust = 1, size = 12, color = "black"),
        axis.text.y = element_text(size = 12, color = "black"),
        axis.title.y = element_text(size = 14, color = "black"),
        axis.title.x = element_blank(), # Remove X-axis title
        legend.position = 'none', # Hide legend if colors are clearly defined by group
        plot.title = element_text(hjust = 0.5, face = "bold"), # Center and bold plot title
        panel.grid.major.y = element_line(color = "gray90", linetype = "dotted"), # Add subtle horizontal grid lines
        panel.grid.minor.y = element_blank(),
        panel.grid.major.x = element_blank() # Remove vertical grid lines if desired
      ) +
      ggplot2::scale_y_continuous(expand = expansion(mult = c(0.05, 0.15))) + # Adjust y-axis expansion for stats
      # Add statistical comparison
      ggpubr::stat_compare_means(
        aes(label = ..p.signif..), # Label with significance stars
        comparisons = comparison_groups, # The pairwise comparisons to perform
        method = "wilcox.test", # Use Wilcoxon test (non-parametric)
        label.y.npc = "top", # Position label near top of plot
        vjust = 0, # Adjust vertical position of label
        size = 4, # Font size of significance label
        tip.length = 0.02, # Length of bracket tips
        bracket.nudge.y = 0.02, # Nudge brackets vertically
        hide.ns = FALSE # Show "ns" for non-significant
      )
    
    modified_plots[[i]] <- p_final
  }
  
  # 4. Combine all modified plots using patchwork
  # ncol determines the number of columns in the final combined plot
  combined_plot <- patchwork::wrap_plots(modified_plots, ncol = ncol)
  
  return(combined_plot)
}
